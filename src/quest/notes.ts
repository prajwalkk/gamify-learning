// Everything Learning Quest writes into the notes folder. Files we generate say so at
// the top; the user's own notes (goal notes, learning log, daily note) are backed up
// before their first edit each day and only touched in the places described.

export const GENERATED = "<!-- Generated by Learning Quest. Edits here are overwritten. -->";
export const QUEST_HEADING = "## 🎯 Today's Quest";
// Sections an earlier version (gamify-learning 0.4) wrote into daily notes; removed when found
const LEGACY_HEADINGS = ["## 📚 Today's Reading", "## 🎯 Learning Goals"];

const rel = (root: string, file: string) => path.relative(root, file);

function readOr(file: string, fallback = ""): string {
  try {
    return fs.readFileSync(file, "utf-8");
  } catch {
    return fallback;
  }
}

/** Write a user's own note: back it up first (once a day), keep its line endings. */
function writeUserNote(root: string, file: string, text: string, eol: string) {
  backupOnce(root, rel(root, file));
  atomicWrite(file, eol === "\r\n" ? text.replace(/\r?\n/g, "\r\n") : text);
}

const eolOf = (text: string) => (text.includes("\r\n") ? "\r\n" : "\n");
const lf = (text: string) => text.replace(/\r\n/g, "\n");

// ── Markdown sections ────────────────────────────────────────────────────────

function sectionBounds(lines: string[], heading: string): { start: number; end: number } | undefined {
  const start = lines.findIndex((l) => l.trim() === heading);
  if (start < 0) return undefined;
  let end = start + 1;
  while (end < lines.length && !/^#{1,2} /.test(lines[end]!) && lines[end]!.trim() !== "---") end++;
  return { start, end };
}

/** Replace our section, or insert it before the note's reflection section (else at the end). */
export function upsertSection(text: string, heading: string, body: string): string {
  const lines = lf(text).split("\n");
  const block = [heading, ...body.replace(/\s+$/, "").split("\n"), ""];
  const found = sectionBounds(lines, heading);
  if (found) {
    lines.splice(found.start, found.end - found.start, ...block);
    return lines.join("\n");
  }
  const reflection = lines.findIndex((l) => /^## .*reflection/i.test(l));
  if (reflection >= 0) {
    lines.splice(reflection, 0, ...block, "---", "");
    return lines.join("\n");
  }
  return `${lines.join("\n").replace(/\s+$/, "")}\n\n---\n\n${block.join("\n")}`;
}

/** Remove a section we wrote, along with the separator that followed it. */
export function removeSection(text: string, heading: string): string {
  const lines = lf(text).split("\n");
  const found = sectionBounds(lines, heading);
  if (!found) return text;
  let end = found.end;
  if (lines[end]?.trim() === "---") {
    end++;
    while (end < lines.length && lines[end]!.trim() === "") end++;
  }
  lines.splice(found.start, end - found.start);
  return lines.join("\n");
}

// ── Templates (Obsidian core-template placeholders) ──────────────────────────

const DAYS = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

export function formatDate(d: Date, fmt: string): string {
  const p = (n: number) => String(n).padStart(2, "0");
  const t: Record<string, () => string> = {
    YYYY: () => String(d.getFullYear()),
    MMMM: () => MONTHS[d.getMonth()]!,
    MMM: () => MONTHS[d.getMonth()]!.slice(0, 3),
    MM: () => p(d.getMonth() + 1),
    M: () => String(d.getMonth() + 1),
    dddd: () => DAYS[d.getDay()]!,
    ddd: () => DAYS[d.getDay()]!.slice(0, 3),
    DD: () => p(d.getDate()),
    D: () => String(d.getDate()),
    HH: () => p(d.getHours()),
    mm: () => p(d.getMinutes()),
  };
  return fmt.replace(/YYYY|MMMM|MMM|MM|M|dddd|ddd|DD|D|HH|mm/g, (k) => t[k]!());
}

export function renderTemplate(tpl: string, d: Date, title: string): string {
  return tpl
    .replace(/\{\{\s*date\s*:\s*([^}]+?)\s*\}\}/g, (_, f) => formatDate(d, f))
    .replace(/\{\{\s*date\s*\}\}/g, formatDate(d, "YYYY-MM-DD"))
    .replace(/\{\{\s*time\s*\}\}/g, formatDate(d, "HH:mm"))
    .replace(/\{\{\s*title\s*\}\}/g, title);
}

// ── Quest Board ──────────────────────────────────────────────────────────────

const bar = (pct: number, width = 10) => "█".repeat(Math.round((pct / 100) * width)).padEnd(width, "░");

export function writeQuestBoard(root: string, state: QuestState, p: Plan, day: string): string {
  const level = levelOf(state.xp);
  const streak = streakOf(state, day);
  const badgeLabels = state.badges.map((b) => BADGES[b.id]?.label ?? b.id);
  const lines: string[] = [
    GENERATED,
    "",
    "# 🧭 Quest Board",
    "",
    `**Level ${level} · ${titleOf(level)}** · ${state.xp} XP (next level at ${nextLevelAt(level)}) · 🔥 ${streak}-day streak (best ${state.bestStreak})`,
    "",
    badgeLabels.length ? `**Badges:** ${badgeLabels.join(" · ")}` : "**Badges:** none yet",
    "",
    "## Goals",
    "",
    "| Goal | Track | Progress | Deadline | Finishes | |",
    "|---|---|---|---|---|---|",
    ...p.goals
      .filter((g) => g.status !== "done")
      .map((g) => `| ${g.title} | ${TRACKS[g.track as keyof typeof TRACKS] ?? g.track} | \`${bar(g.percent)}\` ${g.percent}% | ${g.deadline ? pretty(g.deadline) : "—"} | ${g.finish ? pretty(g.finish) : "—"} | ${g.status === "active" ? (g.atRisk ? "⚠️ at risk" : "▶ active") : g.status} |`),
    "",
  ];
  const done = p.goals.filter((g) => g.status === "done");
  if (done.length) lines.push(`**Done:** ${done.map((g) => `${g.title} (${g.finish ? pretty(g.finish) : ""})`).join(" · ")}`, "");
  lines.push("## Next study days", "");
  for (const d of p.days) {
    const what = d.items.map((i) => `${i.unitTitle} (${i.minutes} min)`).join(", ") || "reading only";
    lines.push(`- **${pretty(d.date)}** · ${d.track ? TRACKS[d.track as keyof typeof TRACKS] ?? d.track : "—"} · ${what}`);
  }
  if (!p.days.length) lines.push("_Nothing planned: add a goal._");
  lines.push("", "## Leaves", "");
  const upcoming = state.leaves.filter((l) => l.to >= day);
  lines.push(...(upcoming.length ? upcoming.map((l) => `- ${pretty(l.from)} – ${pretty(l.to)}${l.reason ? ` · ${l.reason}` : ""}`) : ["_None planned._"]));
  lines.push("", "## Recent sessions", "");
  const recent = [...state.logs].slice(-7).reverse();
  lines.push(
    ...(recent.length
      ? recent.map((l) => `- **${pretty(l.date)}** · ${l.minutes} min${l.quizScore !== undefined ? ` · quiz ${l.quizScore}/10` : ""} · +${l.xp} XP${l.summary ? ` · ${l.summary}` : ""} · [[Learning/Sessions/${l.date}|notes]]`)
      : ["_No sessions yet._"])
  );
  lines.push("");
  const file = path.join(root, "Learning", "Quest Board.md");
  atomicWrite(file, lines.join("\n"));
  return file;
}

// ── Session notes: Learning/Sessions/YYYY-MM-DD.md ───────────────────────────

export function appendSessionNote(root: string, state: QuestState, log: SessionLog): string {
  const file = path.join(root, "Learning", "Sessions", `${log.date}.md`);
  const total = state.logs.filter((l) => l.date === log.date).reduce((n, l) => n + l.minutes, 0);
  let text = lf(readOr(file));
  if (!text) {
    text = `---\nstudy: 0\ntags:\n  - learning-quest\n---\n${GENERATED}\n\n# Study · ${formatDate(parseDay(log.date), "dddd, MMMM D, YYYY")}\n`;
  }
  text = text.replace(/^study:\s*\d+\s*$/m, `study: ${total}`);
  const goal = state.goals.find((g) => g.id === log.goalId);
  const units = (goal?.units ?? []).filter((u) => log.unitsDone.includes(u.id)).map((u) => u.title);
  const time = formatDate(new Date(log.loggedAt), "HH:mm");
  const block = [
    "",
    `## ${time} · ${log.minutes} min`,
    "",
    log.reading ? `- **Reading** (${log.readingMinutes} min): [${log.reading.title}](${log.reading.url})${log.reading.source ? ` · ${log.reading.source}` : ""}` : undefined,
    goal ? `- **Goal:** ${goal.title}${units.length ? ` · finished ${units.join(", ")}` : ""}` : undefined,
    log.stoppedAt ? `- **Stopped at:** ${log.stoppedAt}` : undefined,
    log.quizScore !== undefined ? `- **Quiz:** ${log.quizScore}/10` : undefined,
    log.learned ? `- **Learned:** ${log.learned}` : undefined,
    log.summary ? `- **Summary:** ${log.summary}` : undefined,
    `- **XP:** +${log.xp}`,
  ].filter((l): l is string => l !== undefined);
  atomicWrite(file, text.replace(/\s+$/, "") + "\n" + block.join("\n") + "\n");
  return file;
}

// ── The user's goal note ─────────────────────────────────────────────────────

/** Tick each finished unit's checkbox, add a dated line under "## Progress Log", bump "Last updated". */
export function updateGoalNote(root: string, goal: Goal, unitIds: string[], minutes: number, day: string): string | undefined {
  if (!goal.note) return undefined;
  const file = path.join(root, goal.note.endsWith(".md") ? goal.note : `${goal.note}.md`);
  if (!fs.existsSync(file)) return undefined;
  const original = readOr(file);
  const eol = eolOf(original);
  let text = lf(original);
  const finished = goal.units.filter((u) => unitIds.includes(u.id));
  for (const u of finished) {
    const label = (u.checkbox ?? u.title).trim();
    const esc = label.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    text = text.replace(new RegExp(`^(\\s*[-*] )\\[ \\]( +${esc}\\s*)$`, "m"), "$1[x]$2");
  }
  const entry = `- ${day} · Learning Quest: ${finished.length ? `finished ${finished.map((u) => u.title).join(", ")}` : "studied"} (${minutes} min)`;
  const lines = text.split("\n");
  const at = lines.findIndex((l) => /^##\s+progress log\s*$/i.test(l));
  if (at >= 0) {
    let end = at + 1;
    while (end < lines.length && !/^#{1,2} /.test(lines[end]!)) end++;
    while (end > at + 1 && lines[end - 1]!.trim() === "") end--;
    lines.splice(end, 0, entry);
    text = lines.join("\n");
  } else {
    text = `${text.replace(/\s+$/, "")}\n\n## Progress Log\n\n${entry}\n`;
  }
  text = text
    .replace(/^(\s*\**last[ _-]updated\**:?\**\s*:?\s*)\d{4}-\d{2}-\d{2}/im, `$1${day}`)
    .replace(/^(last_updated|updated):\s*\S+$/m, `$1: ${day}`);
  writeUserNote(root, file, text, eol);
  return file;
}

// ── The user's learning log ──────────────────────────────────────────────────

export function appendLearningLog(root: string, state: QuestState, learned: string, day: string): string {
  const file = path.join(root, state.settings.learningLog);
  const original = readOr(file, `# Learning Log\n`);
  const eol = eolOf(original);
  const lines = lf(original).replace(/\s+$/, "").split("\n");
  const heading = `## ${day}`;
  const at = lines.findIndex((l) => l.trim() === heading);
  const bullets = learned.split(/\n+/).map((l) => l.trim()).filter(Boolean).map((l) => (l.startsWith("- ") ? l : `- ${l}`));
  if (at >= 0) {
    let end = at + 1;
    while (end < lines.length && !/^#{1,2} /.test(lines[end]!)) end++;
    while (end > at + 1 && lines[end - 1]!.trim() === "") end--;
    lines.splice(end, 0, ...bullets);
  } else {
    lines.push("", heading, "", ...bullets);
  }
  writeUserNote(root, file, lines.join("\n") + "\n", eol);
  return file;
}

// ── The user's daily note: "Today's quest" section ───────────────────────────

export function writeDailyQuest(root: string, state: QuestState, t: Today): string | undefined {
  const folder = state.settings.dailyNotesFolder;
  if (!folder || !t.isStudyDay) return undefined;
  const file = path.join(root, folder, `${t.date}.md`);
  let original = readOr(file);
  if (!original) {
    const tpl = readOr(path.join(root, state.settings.dailyTemplate));
    original = tpl ? renderTemplate(tpl, parseDay(t.date), t.date) : `# ${formatDate(parseDay(t.date), "dddd, MMMM D, YYYY")}\n`;
  }
  const eol = eolOf(original);
  let text = lf(original);
  for (const h of LEGACY_HEADINGS) text = removeSection(text, h);
  const lines = [
    `*${t.trackLabel ?? "Study"} day · ${t.minutesToday}/${t.cap} min · 🔥 ${t.streak} · L${t.level} · [[Learning/Quest Board|Quest Board]]*`,
    "",
    // Plain bullets, not checkboxes: this section is regenerated, so a tick here would be lost.
    // Progress is logged through the coach (log_session), and shown here as ✅.
    t.reading
      ? `- 📖 **Reading** (${t.readingBlock} min): [${t.reading.title}](${t.reading.url}) · ${t.reading.source}${t.readingDone ? " ✅" : ""}`
      : `- 📖 **Reading:** none picked yet (refresh the news)`,
    ...(t.goal
      ? t.goal.items.map((i) => `- 🎯 **${t.goal!.title}** · ${i.url ? `[${i.unit}](${i.url})` : i.unit} (${i.minutes} min)`)
      : ["- 🎯 **Goal block:** nothing scheduled"]),
    ...(t.goalMinutesToday ? [`- ✅ ${t.goalMinutesToday} min of goal work logged today`] : []),
    ...t.risk.map((r) => `- ⚠️ ${r.goal} is behind: ${r.option}`),
  ];
  text = upsertSection(text, QUEST_HEADING, lines.join("\n"));
  if (text === lf(readOr(file))) return file;
  if (fs.existsSync(file)) writeUserNote(root, file, text, eol);
  else atomicWrite(file, text);
  return file;
}

/** Snapshot for the Claude Code mod: Learning/.quest/today.json */
export function writeTodaySnapshot(root: string, t: Today): string {
  const file = path.join(questDir(root), "today.json");
  atomicWrite(file, JSON.stringify({ ...t, writtenAt: new Date().toISOString() }, null, 2) + "\n");
  return file;
}
